import { describe, expect, test } from "bun:test";
import { GENERATOR_VERSION } from "../src/core/version";
import type { Preset } from "../src/core/types";
import { buildGoldenGen, compareGoldenGen, type GoldenGen } from "./golden/golden-gen";

const fjord = (await Bun.file(new URL("../presets/fjord-coast.json", import.meta.url)).json()) as Preset;
// named after the version that wrote it (scripts/golden.ts): a GENERATOR_VERSION bump needs a new file
const file = `gen-${GENERATOR_VERSION.split("/")[1]}.json`;
const stored = (await Bun.file(new URL(`./golden/${file}`, import.meta.url)).json()) as GoldenGen;

describe("golden master (generator)", () => {
  test(`${file} matches the live generator on fjord-coast across block boundaries`, () => {
    expect(compareGoldenGen(stored, buildGoldenGen(fjord))).toEqual([]);
  });

  test("golden file was generated by the current GENERATOR_VERSION", () => {
    expect(stored.generatorVersion).toBe(GENERATOR_VERSION);
  });
});
